void MarchingCubes::Generate(int _width, int _height, int _length, float _isoLevel, const TerrainParams& terrain) {
    
    m_width = _width;
    m_height = _height;
    m_length = _length;
    
    // Seed -> fixed random offset in noise space
    std::mt19937 rng(terrain.seed);
    std::uniform_real_distribution<float> dist(0.f, 1000.f);
    const glm::vec3 seedOffset(dist(rng), dist(rng), dist(rng));
    
    VoxelGrid grid(m_width,m_height,m_length);
    
    for (int z = 0; z < m_length; z++) {
        for (int y = 0; y < m_height; y++) {
            for (int x = 0; x < m_width; x++) {
                float value = Density(glm::vec3(x, y, z), m_height, terrain, seedOffset);

                // Closed borders: solid floor, open sky
                if (y == 0)            value = -1.f;
                if (y == m_height - 1) value =  1.f;

                grid.write(value, x, y, z);
            }
        }
    }
    
    std::vector<glm::vec3> vertices;
    std::vector<uint32> indices;
    std::vector<int32_t> edgeCache(static_cast<size_t>(m_width) * m_height * m_length * 3, -1);
    for (int z = 0; z < m_length - 1; z++)
        for (int y = 0; y < m_height - 1; y++)
            for (int x = 0; x < m_width - 1; x++)
                MarchCube(x,y,z,grid, vertices, indices, edgeCache, _isoLevel);
    
    // Smooth normals from the density gradient (central differences)
    std::vector<Vertex> trueVertices(vertices.size());
    #pragma omp parallel for
    for (size_t i = 0; i < vertices.size(); i++) {
        const glm::vec3& p = vertices[i];
    
        glm::vec3 grad(
            Density(p + glm::vec3(1.0f, 0, 0), m_height, terrain, seedOffset) - Density(p - glm::vec3(1.0f, 0, 0), m_height, terrain, seedOffset), // Gradient/Derivative of Density for x
            Density(p + glm::vec3(0, 1.0f, 0), m_height, terrain, seedOffset) - Density(p - glm::vec3(0, 1.0f, 0), m_height, terrain, seedOffset), // Gradient/Derivative of Density for y
            Density(p + glm::vec3(0, 0, 1.0f), m_height, terrain, seedOffset) - Density(p - glm::vec3(0, 0, 1.0f), m_height, terrain, seedOffset)); // Gradient/Derivative of Density for z
    
        trueVertices[i].pos = p;
        trueVertices[i].color = {1.f, 1.f, 1.f, 1.f};
        // The density increases toward the air, so the gradient points outward
        trueVertices[i].normal = glm::length(grad) > 1e-6f ? glm::normalize(grad) : glm::vec3(0, 1, 0);
    }
    
    m_geometry = Geometry(trueVertices, indices);
}

const Geometry* MarchingCubes::GetGeometry() const {
    return &m_geometry;
}

std::array<int, 16> MarchingCubes::GetTriangulation(int x, int y, int z, VoxelGrid& grid, float _isoLevel) {
    int idx = 0b00000000;
    idx |= static_cast<int>(grid.read(x,y,z) < _isoLevel) << 0;
    idx |= static_cast<int>(grid.read(x,y,z+1) < _isoLevel) << 1;
    idx |= static_cast<int>(grid.read(x+1,y,z+1) < _isoLevel) << 2;
    idx |= static_cast<int>(grid.read(x+1,y,z) < _isoLevel) << 3;
    idx |= static_cast<int>(grid.read(x,y+1,z) < _isoLevel) << 4;
    idx |= static_cast<int>(grid.read(x,y+1,z+1) < _isoLevel) << 5;
    idx |= static_cast<int>(grid.read(x+1,y+1,z+1) < _isoLevel) << 6;
    idx |= static_cast<int>(grid.read(x+1,y+1,z) < _isoLevel) << 7;
    return TRI_TABLE[idx];
}

glm::vec3 MarchingCubes::CalculateInterpolation(glm::ivec3 a,glm::ivec3 b, VoxelGrid& grid, float _isoLevel) 
{
    float val_a = grid.read(a.x,a.y,a.z);
    float val_b = grid.read(b.x,b.y,b.z);
    float d = val_b - val_a;
    float t = (std::abs(d) < 1e-6f) ? 0.5f : (_isoLevel - val_a) / d;
    return glm::vec3(a)+t * glm::vec3(b-a);
}

static uint64 EdgeKey(glm::ivec3 a, glm::ivec3 b, int width, int height) {
    // Swap b and a so a is always the lower corner
    if (b.x < a.x || b.y < a.y || b.z < a.z) 
        std::swap(a, b);
    // identify on which axis is the edge : +x, +y or +z (-> because a is always the lower corner)
    int axis = (a.x != b.x) ? 0 : (a.y != b.y) ? 1 : 2;
    // Compute the coordinate in a 1D array
    uint64 cell = (static_cast<uint64>(a.z) * height + a.y) * width + a.x;
    // Times 3 because we have 3 axis per lower corner
    return cell * 3 + axis;
}

void MarchingCubes::MarchCube(int x, int y, int z, VoxelGrid& grid, std::vector<glm::vec3>& vertices, std::vector<uint32>& indices, std::vector<int32>& edgeCache, float _isoLevel) const {
    // Get the correct configuration
    std::array<int, 16> tri = GetTriangulation(x, y, z, grid, _isoLevel);
    for (int edge_index : tri) 
    {
        if (edge_index < 0) 
            break;
       // Get edge
       glm::ivec2 point_indices = EDGES[edge_index];
       // Get 2 points connecting this edge
       glm::ivec3 p0 = POINTS[point_indices.x];
       glm::ivec3 p1 = POINTS[point_indices.y];
       // Global position of these 2 points
       glm::ivec3 pos_a = glm::ivec3(x+p0.x, y+p0.y, z+p0.z);
       glm::ivec3 pos_b = glm::ivec3(x+p1.x, y+p1.y, z+p1.z);
        
        // We can cache vertices since an edge between 2 pos will always give us the same result
        uint64_t key = EdgeKey(pos_a, pos_b, m_width, m_height);

        if (edgeCache[key] < 0) {
            edgeCache[key] = static_cast<int32_t>(vertices.size());
            // Interpolate between these 2 points to get our mesh's vertex position
            glm::vec3 position = CalculateInterpolation(pos_a, pos_b, grid, _isoLevel);
            // Add our new vertex to our mesh's vertices array
            vertices.push_back(position);
        }
        indices.push_back(static_cast<uint32_t>(edgeCache[key]));
    }
}

float MarchingCubes::Density(const glm::vec3& pos, int height, const TerrainParams& t, const glm::vec3& seedOffset) {
    glm::vec3 p = pos * t.frequency + seedOffset;

    float ground = (pos.y - t.groundLevel * height) / (t.heightScale * height);
    float hills  = FractalBrownianMotion(glm::vec2(p.x, p.z), t.hillOctaves, t.lacunarity, t.persistence);
    float detail = FractalBrownianMotion(p * 2.f, t.detailOctaves, t.lacunarity, t.persistence);

    return ground - hills * t.hillAmp - detail * t.detailAmp;
}
